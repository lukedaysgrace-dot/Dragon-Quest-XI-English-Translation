#!/usr/bin/env python3
"""item.bxon name fields: the Japanese puts a line break into long names ('イシの\\nつるぎ') because the
battle target window (bottom screen) is narrow; lists show the name on one line ('\\n' is dropped there).
English names longer than ~15 chars whose Japanese had no break get one at a word boundary -> id overrides,
only for item.bxon (the same Japanese text is shared by other tables where a break would be wrong).
Usage: mk_item2line.py <db> <62_items.json> <out.json>"""
import sys, json, re, sqlite3
db = sqlite3.connect(sys.argv[1]); tm = json.load(open(sys.argv[2], encoding='utf-8'))['tm']
norm = lambda s: re.sub(r'\{ruby:([^|]*)\|[^}]*\}', r'\1', s)
ntm = {norm(k): v for k, v in tm.items()}
def split(v):
    words = v.split(' '); best = None
    for i in range(1, len(words)):
        a, b = ' '.join(words[:i]), ' '.join(words[i:])
        if len(a) <= 15 and len(b) <= 16:
            sc = max(len(a), len(b))
            if best is None or sc < best[0]: best = (sc, a + ' \n' + b)
    return best[1] if best else None
out = {}
for sid, jp in db.execute("select id, jp from strings where id like '/syscmn.pack|item.bxon|%'"):
    j = norm(jp)
    if '\n' in j or len(j) > 14 or j not in ntm: continue
    v = ntm[j]
    if '\n' in v or len(v) <= 15 or ' ' not in v: continue
    s = split(v)
    if s: out[sid] = s
json.dump({'status': 'translated', 'source': 'fan', '_comment': 'generated by maps/mk_item2line.py', 'id': out},
          open(sys.argv[3], 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(len(out), 'item name fields broken into 2 lines')
