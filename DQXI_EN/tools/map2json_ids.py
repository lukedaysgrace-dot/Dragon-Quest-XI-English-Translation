#!/usr/bin/env python3
"""Map {(pack, entry, offset): (src, english)} -> per-id translation files (<prefix>_official.json / _fan.json)."""
import sys, json, sqlite3, runpy
mp, dbp, outp = sys.argv[1:4]
M = runpy.run_path(mp)['M']
db = sqlite3.connect(dbp)
out = {'o': {}, 'f': {}}; miss = []
for (pack, entry, off), (src, en) in M.items():
    sid = '%s|%s|%x' % (pack, entry, off)
    if not db.execute('select 1 from strings where id=?', (sid,)).fetchone(): miss.append(sid); continue
    out[src][sid] = en
for src, name in (('o', 'official'), ('f', 'fan')):
    if out[src]:
        json.dump({'status': 'translated', 'source': 'official' if src == 'o' else 'fan',
                   '_comment': 'generated by map2json_ids.py from ' + mp.split('/')[-1], 'id': out[src]},
                  open('%s_%s.json' % (outp, name), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('official', len(out['o']), 'fan', len(out['f']), 'missing', miss)
