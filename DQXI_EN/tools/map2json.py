#!/usr/bin/env python3
"""Turn an offset->(src, english) map for one BXON into translation files.
Usage: map2json.py <map.py> <db> <pack> <entry> <out_prefix> [--by-id]
Writes <out_prefix>_official.json (src 'o') and <out_prefix>_fan.json (src 'f').
Default: keyed by Japanese text (translation memory -> identical lines elsewhere reuse it);
--by-id: keyed by string id (only this exact string)."""
import sys, json, sqlite3, re, runpy
RUBY = re.compile(r'\{ruby:([^|{}]*)\|[^{}]*\}')
mp, dbp, pack, entry, outp = sys.argv[1:6]
by_id = '--by-id' in sys.argv
M = runpy.run_path(mp)['M']
db = sqlite3.connect(dbp)
out = {'o': {}, 'f': {}}
miss = []
for off, (src, en) in M.items():
    sid = '%s|%s|%x' % (pack, entry, off)
    r = db.execute('select jp from strings where id=?', (sid,)).fetchone()
    if not r: miss.append(hex(off)); continue
    key = sid if by_id else RUBY.sub(r'\1', r[0])
    out[src][key] = en
for src, name in (('o', 'official'), ('f', 'fan')):
    if not out[src]: continue
    d = {'status': 'translated', 'source': 'official' if src == 'o' else 'fan',
         '_comment': 'generated by map2json.py from %s (%s)' % (mp.split('/')[-1], pack + '|' + entry),
         ('id' if by_id else 'tm'): out[src]}
    json.dump(d, open('%s_%s.json' % (outp, name), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('official', len(out['o']), 'fan', len(out['f']), 'missing', miss)
